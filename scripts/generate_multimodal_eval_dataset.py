def get_font(size):
    try:
        return ImageFont.truetype(FONT_PATH, size)
    except IOError:
        return ImageFont.load_default()


def draw_business_chart(draw, width, height):
    # Draw axes
    draw.line([(50, height - 50), (width - 50, height - 50)], fill="black", width=2)
    draw.line([(50, height - 50), (50, 50)], fill="black", width=2)

    # Draw bars
    colors = ["#4c72b0", "#dd8452", "#55a868", "#c44e52"]
    bar_width = (width - 150) // 4
    for i in range(4):
        x0 = 80 + i * (bar_width + 10)
        y0 = random.randint(100, height - 60)
        x1 = x0 + bar_width
        y1 = height - 51
        draw.rectangle([x0, y0, x1, y1], fill=colors[i])


def draw_document_layout(draw, width, height):
    # Draw document borders and lines
    draw.rectangle([20, 20, width - 20, height - 20], outline="black", width=2)
    # Title line
    draw.line([(20, 80), (width - 20, 80)], fill="black", width=1)
    # Table headers
    draw.line([(20, 150), (width - 20, 150)], fill="black", width=1)
    draw.line([(20, 180), (width - 20, 180)], fill="black", width=1)
    # Columns
    draw.line([(width // 2, 150), (width // 2, height - 20)], fill="black", width=1)


def draw_ui_system_screen(draw, width, height):
    # Window frame
    draw.rectangle(
        [10, 10, width - 10, height - 10], outline="gray", width=3, fill="#f0f0f0"
    )
    draw.rectangle([10, 10, width - 10, 40], fill="darkgray")
    # Buttons
    draw.rectangle([20, 20, 30, 30], fill="red")
    draw.rectangle([40, 20, 50, 30], fill="yellow")
    draw.rectangle([60, 20, 70, 30], fill="green")

    # Content area
    draw.rectangle([30, 60, width - 30, height - 30], fill="white", outline="gray")
    for i in range(5):
        draw.line(
            [(50, 90 + i * 30), (width - 50, 90 + i * 30)], fill="lightgray", width=2
        )


def draw_technical_diagram(draw, width, height):
    # Nodes
    nodes = [
        (width // 4, height // 2 - 30, width // 4 + 80, height // 2 + 30, "#d9ead3"),
        (
            width // 2 - 20,
            height // 2 - 30,
            width // 2 + 60,
            height // 2 + 30,
            "#c9daf8",
        ),
        (
            3 * width // 4 - 40,
            height // 2 - 30,
            3 * width // 4 + 40,
            height // 2 + 30,
            "#fce5cd",
        ),
    ]
    for x0, y0, x1, y1, color in nodes:
        draw.rectangle([x0, y0, x1, y1], fill=color, outline="black", width=2)

    # Arrows
    draw.line(
        [(nodes[0][2], height // 2), (nodes[1][0], height // 2)], fill="black", width=3
    )
    draw.polygon(
        [
            (nodes[1][0], height // 2),
            (nodes[1][0] - 10, height // 2 - 5),
            (nodes[1][0] - 10, height // 2 + 5),
        ],
        fill="black",
    )

    draw.line(
        [(nodes[1][2], height // 2), (nodes[2][0], height // 2)], fill="black", width=3
    )
    draw.polygon(
        [
            (nodes[2][0], height // 2),
            (nodes[2][0] - 10, height // 2 - 5),
            (nodes[2][0] - 10, height // 2 + 5),
        ],
        fill="black",
    )


