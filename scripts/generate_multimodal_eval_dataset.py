def generate_images(dataset):
    os.makedirs(IMAGE_DIR, exist_ok=True)
    for item in dataset:
        width, height = random.randint(400, 600), random.randint(300, 400)
        img = Image.new("RGB", (width, height), color="white")
        draw = ImageDraw.Draw(img)
        font = get_font(20)

        # Draw category specific graphics
        cat = item["category"]
        if cat == "business_charts":
            draw_business_chart(draw, width, height)
        elif cat == "document_layouts":
            draw_document_layout(draw, width, height)
        elif cat == "ui_system_screens":
            draw_ui_system_screen(draw, width, height)
        elif cat == "technical_diagrams":
            draw_technical_diagram(draw, width, height)

        # Add title text (using query as title snippet)
        title = item["query"][:15] + "..."
        draw.text((10, 10), title, font=font, fill="black")

        img.save(item["image_path"])


def generate_markdown(dataset):
    os.makedirs(os.path.dirname(MD_PATH), exist_ok=True)
    with open(MD_PATH, "w", encoding="utf-8") as f:
        f.write("# マルチモーダル評価データセット 目視点検シート\n\n")
        f.write("以下のリストは生成されたデータセットの目視点検用です。\n")
        f.write(
            "各項目について、「画像・クエリ・正解/ニアミス説明」の整合性を確認してください。\n\n"
        )

        f.write("## 点検チェックリスト\n")
        f.write("- [ ] 解像度や画像の視認性に問題はないか\n")
        f.write("- [ ] テキスト（クエリ等）が画像と適切に対応しているか\n")
        f.write(
            "- [ ] 正解説明（Positive）とニアミス説明（Hard Negative）の意味の対比が明確で、難易度が適切か\n\n"
        )

        for item in dataset:
            f.write(f"### ID: {item['id']} ({item['category']})\n")
            # Correct relative path for the image from docs/infrastructure/
            # MD_PATH is docs/infrastructure/dataset_multimodal_visual_inspection.md
            # IMAGE_DIR is benchmarks/datasets/multimodal_images
            rel_image_path = f"../../benchmarks/datasets/multimodal_images/{os.path.basename(item['image_path'])}"
            f.write(f"![{item['id']}]({rel_image_path})\n\n")
            f.write(f"- **Query**: {item['query']}\n")
            f.write(f"- **Positive Description**: {item['positive_description']}\n")
            f.write(
                f"- **Hard Negative Description**: {item['hard_negative_description']}\n\n"
            )
            f.write("---\n\n")


def main():
    parser = argparse.ArgumentParser(
        description="Generate multimodal evaluation dataset"
    )
    parser.add_argument(
        "--inspect-md", action="store_true", help="Generate inspection markdown"
    )
    parser.parse_args()

    print("Generating dataset definitions...")
    dataset = generate_data()

    print("Generating images...")
    generate_images(dataset)

    print(f"Saving JSON metadata to {JSON_PATH}...")
    os.makedirs(os.path.dirname(JSON_PATH), exist_ok=True)
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(dataset, f, ensure_ascii=False, indent=2)

    print("Generating markdown inspection sheet...")
    generate_markdown(dataset)

    print("Dataset generation complete!")


if __name__ == "__main__":
    main()
